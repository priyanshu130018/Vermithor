class Investigation(Base):
    """Database model for persisted incident investigations conducted by the LangGraph agent."""

    __tablename__ = "investigations"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True).with_variant(PG_UUID(as_uuid=True), "postgresql"),
        primary_key=True,
        default=uuid.uuid4,
    )
    investigation_key: Mapped[str] = mapped_column(
        String(64),
        unique=True,
        index=True,
        nullable=False,
    )
    org_id: Mapped[str] = mapped_column(
        String(64),
        index=True,
        nullable=False,
        default="vermithor",
        server_default="vermithor",
    )
    incident_key: Mapped[str] = mapped_column(
        String(64),
        index=True,
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        String(32),
        index=True,
        nullable=False,
        default="PENDING",
    )
    target_service: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        default="unknown",
    )
    environment: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        default="production",
    )
    leading_hypothesis: Mapped[Optional[str]] = mapped_column(
        String(255),
        nullable=True,
    )
    confidence: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )
    is_fallback: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
    )
    model_provider: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        default="unknown",
    )
    model_name: Mapped[Optional[str]] = mapped_column(
        String(128),
        nullable=True,
    )
    report_json: Mapped[Optional[Dict[str, Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"),
        nullable=True,
    )
    evidence_json: Mapped[Optional[List[Dict[str, Any]]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"),
        nullable=True,
    )
    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    completed_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )


