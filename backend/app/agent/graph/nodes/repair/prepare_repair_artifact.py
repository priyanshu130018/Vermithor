import logging
from typing import Any, Dict, Optional

from backend.app.agent.git.base import GitProvider
from backend.app.agent.graph.repair_state import RepairState
from backend.app.agent.schemas.repair import RepairReport, TestExecutionResult, ValidationStatus

logger = logging.getLogger(__name__)


def prepare_repair_artifact_node(
    state: RepairState,
    git_provider: Optional[GitProvider] = None,
) -> Dict[str, Any]:
    """
    Assemble the complete, reviewable RepairReport artifact. If configured and authorized,
    creates a repair branch and draft pull request through the GitProvider.
    """
    repair_key = state.get("repair_key", "")
    incident_key = state.get("incident_key", "")
    investigation_key = state.get("investigation_key", "")
    repo_url = state.get("repository_url") or "workspace"
    target_branch = state.get("target_branch") or "main"
    auto_create_pr = state.get("auto_create_pr", False)

    branch_name = f"repair/{incident_key.lower()}-{repair_key.lower()}"
    pr_url: Optional[str] = None
    pr_number: Optional[int] = None

    # Git operations if provider is available
    if git_provider and state.get("is_authorized", False):
        try:
            # Create branch record
            git_provider.create_branch(repo_url, branch_name, base_ref=target_branch)

            # Create draft PR if requested
            if auto_create_pr:
                title = f"[Vermithor Repair] Fix defect for {incident_key}"
                body = f"""## Vermithor Automated Code Repair Proposal

**Incident:** {incident_key}
**Investigation:** {investigation_key}
**Repair Key:** {repair_key}

### Suspected Defect
{state.get("suspected_defect", "See investigation report.")}

### Validation Outcome
Status: {state.get("validation_status", "PENDING")}

> **Important**: This pull request was generated by Vermithor's AI Code Repair Agent.
> Explicit human review and approval is strictly required before merging.
"""
                pr_record = git_provider.create_pull_request(
                    repository_url=repo_url,
                    title=title,
                    body=body,
                    head_branch=branch_name,
                    base_branch=target_branch,
                )
                pr_url = pr_record.get("html_url")
                pr_number = pr_record.get("number")
        except Exception as exc:
            logger.warning("Git provider branch or PR preparation encountered error: %s", exc)

    # Format validation result
    val_dict = state.get("validation_result")
    val_obj = TestExecutionResult.model_validate(val_dict) if val_dict else None

    has_patch = bool(state.get("proposed_patch"))
    requires_approval = state.get("requires_human_approval")
    if requires_approval is None:
        requires_approval = has_patch
    elif not has_patch:
        requires_approval = False

    # Assemble complete RepairReport
    report = RepairReport(
        incident_key=incident_key,
        investigation_key=investigation_key,
        suspected_defect=state.get("suspected_defect") or "Defect undetermined",
        evidence_citations=state.get("evidence_citations") or [],
        inspected_files=state.get("inspected_file_paths") or list((state.get("inspected_files") or {}).keys()),
        files_and_lines_to_modify=[{"file": f} for f in (state.get("files_changed") or [])],
        proposed_patch=state.get("proposed_patch"),
        patch_hash=state.get("patch_hash"),
        expected_behavior=state.get("expected_behavior") or "Service operates within normal error and latency bounds",
        potential_regressions=state.get("potential_regressions") or [],
        security_implications=state.get("security_implications") or [],
        tests_required=state.get("test_commands") or ["pytest"],
        remaining_uncertainty="Passing sandbox tests do not guarantee a production fix under real traffic concurrency.",
        validation_result=val_obj,
        pull_request_url=pr_url,
        pull_request_number=pr_number,
        requires_human_approval=requires_approval,
        model_provider=state.get("model_provider", "unknown"),
        model_name=state.get("model_name"),
        is_fallback=state.get("is_fallback", False),
    )

    logger.info("Prepared repair artifact for %s (PR: %s)", repair_key, pr_url)

    return {
        "repair_branch": branch_name,
        "pull_request_url": pr_url,
        "pull_request_number": pr_number,
        "requires_human_approval": requires_approval,
        "report": report.model_dump(),
    }
